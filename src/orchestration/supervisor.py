"""
JARVIS Hierarchical Supervisor & AST Validation Gates Interface
Reference abstraction demonstrating DAG decomposition and safety gates.
"""

import ast
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, List, Optional, Set


class TaskPriority(Enum):
    LOW = 1
    MEDIUM = 2
    HIGH = 3
    CRITICAL = 4


@dataclass
class DAGNode:
    """Represents an atomic task node within an execution graph."""
    node_id: str
    action_type: str
    payload: Dict
    priority: TaskPriority = TaskPriority.MEDIUM
    dependencies: Set[str] = field(default_factory=set)
    completed: bool = False
    result: Optional[Dict] = None


class ASTValidationError(Exception):
    """Raised when generated code fails static AST validation gates."""
    pass


class ASTValidationGate:
    """Multi-layer AST verification gate for dynamically generated agent code."""

    FORBIDDEN_CALLS = {
        "os.system",
        "subprocess.Popen",
        "subprocess.call",
        "shutil.rmtree",
        "builtins.eval",
        "builtins.exec",
    }

    @classmethod
    def validate_code_snippet(cls, source_code: str) -> bool:
        """Parses source code into an AST and verifies safety against destructive calls.
        
        Args:
            source_code: Python string generated by an agent.

        Returns:
            True if the snippet passes all static security assertions.

        Raises:
            ASTValidationError: If syntax is invalid or blacklisted calls are found.
        """
        try:
            tree = ast.parse(source_code)
        except SyntaxError as e:
            raise ASTValidationError(f"Syntax validation failed: {e}") from e

        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                call_name = cls._resolve_call_name(node.func)
                if call_name in cls.FORBIDDEN_CALLS:
                    raise ASTValidationError(
                        f"Security violation: call to prohibited routine '{call_name}' detected."
                    )
        return True

    @staticmethod
    def _resolve_call_name(func_node: ast.AST) -> str:
        """Recursively resolves module.attribute call names."""
        if isinstance(func_node, ast.Name):
            return func_node.id
        elif isinstance(func_node, ast.Attribute):
            value = ASTValidationGate._resolve_call_name(func_node.value)
            return f"{value}.{func_node.attr}" if value else func_node.attr
        return ""


class BaseSupervisorOrchestrator(ABC):
    """Abstract contract for the Hierarchical DAG Supervisor."""

    @abstractmethod
    def plan_directive(self, objective: str) -> List[DAGNode]:
        """Decomposes a high-level goal into a dependency-ordered task graph."""
        pass

    @abstractmethod
    def dispatch_worker(self, node: DAGNode) -> Dict:
        """Dispatches an atomic node to an isolated worker subagent."""
        pass
